import DogmaIDs
import Foundation
import SQLite3

/// Fails the build when the main database was built from a different SDE than DogmaKit.
///
/// Usage: `SDEVersionCheck <sde.sqlite> <output.swift>`.

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("error: \(message)\n".utf8))
    exit(1)
}

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
    fail("usage: SDEVersionCheck <sde.sqlite> <output.swift>")
}
let databasePath = arguments[1]
let outputPath = arguments[2]
let fix = "rebuild the databases with `swift package --allow-writing-to-package-directory build-sde` "
    + "from SDE dump \(SDEVersion.buildNumber), or update DogmaKit to the build of the databases"

func readBuildNumber(_ path: String) -> Int? {
    var db: OpaquePointer?
    defer { sqlite3_close(db) }
    guard sqlite3_open_v2(path, &db, SQLITE_OPEN_READONLY, nil) == SQLITE_OK else { return nil }
    var statement: OpaquePointer?
    defer { sqlite3_finalize(statement) }
    guard sqlite3_prepare_v2(db, "SELECT buildNumber FROM meta LIMIT 1", -1, &statement, nil) == SQLITE_OK,
          sqlite3_step(statement) == SQLITE_ROW,
          sqlite3_column_type(statement, 0) == SQLITE_INTEGER
    else { return nil }
    return Int(sqlite3_column_int64(statement, 0))
}

guard FileManager.default.fileExists(atPath: databasePath) else {
    fail("\(databasePath) is missing; \(fix)")
}
guard let buildNumber = readBuildNumber(databasePath) else {
    fail("cannot read meta.buildNumber from \(databasePath); \(fix)")
}
guard buildNumber == SDEVersion.buildNumber else {
    fail("SDE build mismatch: \(databasePath) is SDE \(buildNumber), DogmaKit is SDE \(SDEVersion.buildNumber); \(fix)")
}

let output = """
    // Generated by SDEVersionCheck.

    let checkedSDEBuildNumber = \(buildNumber)

    """
do {
    try output.write(toFile: outputPath, atomically: true, encoding: .utf8)
} catch {
    fail("cannot write \(outputPath): \(error)")
}
